// ai-explainer.js - Handles AI-driven explanations for courses

function openAiExplainer(courseName) {
    const modal = document.getElementById('aiModal');
    const titleEl = document.getElementById('aiCourseTitle');
    const contentEl = document.getElementById('aiModalContent');
    const closeBtn = document.getElementById('aiModalClose');
    
    if (!modal || !titleEl || !contentEl) {
        console.error("AI Explainer Modal elements not found.");
        return;
    }
    
    // Show modal and loading state
    modal.style.display = 'flex';
    titleEl.textContent = `Analyzing: ${courseName}...`;
    contentEl.innerHTML = `
        <div style="text-align: center; padding: var(--space-8);">
            <i class="fa-solid fa-spinner fa-spin fa-2xl" style="color: var(--color-primary-500);"></i>
            <p style="margin-top: var(--space-4);">Analyzing course curriculum & career outcomes...</p>
        </div>
    `;
    
    // Setup close button
    if (closeBtn) {
        closeBtn.onclick = () => {
            modal.style.display = 'none';
            if (window.TTSManager) window.TTSManager.stop();
        };
    }
    
    // Click outside to close
    modal.onclick = (e) => {
        if (e.target === modal) {
            modal.style.display = 'none';
            if (window.TTSManager) window.TTSManager.stop();
        }
    };
    
    // Simulate AI generation delay
    setTimeout(() => {
        let content = `This course provides a comprehensive overview of ${courseName}. It is designed to equip students with the theoretical foundation and practical skills needed for a successful career. Graduates often find opportunities in leading companies with starting salaries ranging from ₹4-8 Lakhs per annum depending on their skill level and internships.`;
        
        if (courseName.toLowerCase().includes('computer') || courseName.toLowerCase().includes('it')) {
            content = `${courseName} is a highly sought-after field focusing on software development, algorithms, and systems engineering. The IT sector offers some of the highest placement rates in India, with numerous opportunities in MNCs and startups alike.`;
        } else if (courseName.toLowerCase().includes('medical') || courseName.toLowerCase().includes('mbbs')) {
            content = `${courseName} is a rigorous program preparing students for a noble career in healthcare. It involves extensive clinical practice and theoretical learning.`;
        }
        
        titleEl.textContent = courseName;
        contentEl.innerHTML = `
            <p style="color: var(--color-neutral-700); line-height: 1.6; margin-bottom: var(--space-4);">${content}</p>
            <div style="font-size: var(--text-sm); color: var(--color-neutral-500); display: flex; align-items: center; gap: var(--space-2); border-top: 1px solid var(--color-neutral-200); padding-top: var(--space-2);">
                <i class="fa-solid fa-robot"></i> Generated by AI Assistant
            </div>
        `;
    }, 1200);
}
